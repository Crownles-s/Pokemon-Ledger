"""Validate the generated Pokédex data and static entry points."""
import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class HTMLCheck(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids = set()
        self.scripts = []
        self.styles = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            assert a["id"] not in self.ids, f"duplicate HTML id: {a['id']}"
            self.ids.add(a["id"])
        if tag == "script" and "src" in a:
            self.scripts.append(a["src"])
        if tag == "link" and a.get("rel") == "stylesheet":
            self.styles.append(a["href"])


for name in ("index.html", "ledger.html", "pokedex.html"):
    check = HTMLCheck()
    check.feed((ROOT / name).read_text(encoding="utf-8"))
    for path in check.scripts + check.styles:
        if path.startswith(("https://", "http://")):
            continue
        assert (ROOT / path).is_file(), f"{name}: missing {path}"
    if name == "ledger.html":
        assert {"teamGrid", "editor", "savedTeams", "gameSelect", "importFile"} <= check.ids
        assert "team-builder.js" in check.scripts

for name in ("styles.css", "design.css", "ledger.css", "ledger-base.css", "theme.css"):
    css = (ROOT / name).read_text(encoding="utf-8")
    for imported in re.findall(r"@import\s+url\(['\"]([^'\"]+)['\"]\)", css):
        assert (ROOT / name).parent.joinpath(imported).is_file(), f"{name}: missing import {imported}"

text = (ROOT / "data/dex.js").read_text(encoding="utf-8")
assert text.startswith("/* Generated by scripts/build_dex.py")
data = json.loads(text[text.index("const DEX=") + len("const DEX=") :].rstrip(";\n"))
species = data["species"]
pokemon = data["pokemon"]
moves = data["moves"]
abilities = data["abilities"]
items = data["items"]
assert (len(species), len(pokemon), len(moves), len(abilities), len(items)) == (1025, 1351, 938, 374, 2223)
assert all(str(p["species"]) in species for p in pokemon.values())
assert all(str(a["id"]) in abilities for p in pokemon.values() for a in p["abilities"])
assert all(str(s["evolvesFrom"]) in species for s in species.values() if s["evolvesFrom"])
assert all(str(r["item"]) in items for entries in data["evolutions"].values() for r in entries if r["item"])
assert all(str(mid) in moves for versions in data["learnsets"].values() for entries in versions.values() for mid, _, _ in entries)
assert all(str(pid) in pokemon for versions in data["learnsets"].values() for pid in versions)
assert any(versions.get("1") for versions in data["learnsets"].values())
assert pokemon["1"]["types"] == ["Grass", "Poison"]
assert pokemon["1"]["stats"]["hp"] == 45
assert pokemon["10034"]["types"] == ["Fire", "Dragon"] and pokemon["10034"]["mega"]
assert any(a["id"] == 65 for a in pokemon["1"]["abilities"])
assert data["learnsets"]["25"].get("1"), "Bulbasaur learnset missing in Scarlet/Violet"
assert any(item["description"] for item in items.values())
assert all(re.fullmatch(r"[a-z0-9-]+", item["sprite"]) for item in items.values())
assert items["1"]["sprite"] == "master-ball" and items["698"]["sprite"] == "venusaurite"
assert species["1"]["genus"] and species["1"]["eggGroups"]
assert species["1"]["genderRate"] == 1
assert any(e["version"] in data["versions"] or str(e["version"]) in data["versions"] for e in species["1"]["entries"])
assert moves["1"]["target"] and moves["1"]["entries"]
assert data["typeChart"]["Fire"]["Grass"] == 2
assert len(data["natures"]) == 25
assert {n["name"] for n in data["natures"].values()} == {"Hardy", "Lonely", "Brave", "Adamant", "Naughty", "Bold", "Docile", "Relaxed", "Impish", "Lax", "Timid", "Hasty", "Serious", "Jolly", "Naive", "Modest", "Mild", "Quiet", "Bashful", "Rash", "Calm", "Gentle", "Sassy", "Careful", "Quirky"}
adamant = next(n for n in data["natures"].values() if n["name"] == "Adamant")
assert (adamant["increased"], adamant["decreased"]) == ("attack", "special-attack")
assert all(n["increased"] == n["decreased"] for n in data["natures"].values() if n["name"] in {"Hardy", "Docile", "Bashful", "Quirky", "Serious"})
nature_axes = {"attack", "defense", "special-attack", "special-defense", "speed"}
assert {(n["increased"], n["decreased"]) for n in data["natures"].values()} == {(up, down) for up in nature_axes for down in nature_axes}
assert pokemon["1"]["effort"] and pokemon["1"]["baseExperience"]
assert all(e[0] in [v["id"] for v in data["versions"].values()] for e in pokemon["1"].get("encounters", []))
mega_source = (ROOT / "data/mega.js").read_text(encoding="utf-8")
def mega_map(name):
    block = re.search(rf"const {name} = \{{(.*?)\}};", mega_source, re.S)
    assert block, f"missing Mega mapping: {name}"
    return {int(form): int(target) for form, target in re.findall(r"(\d+):(\d+)", block.group(1))}

stone_species = mega_map("stoneBySpecies")
stone_forms = mega_map("stoneByForm")
base_forms = mega_map("baseByForm")
primal_orbs = mega_map("primalOrbByForm")
assert primal_orbs == {10077: 468, 10078: 467}
assert items["467"]["name"] == "Red Orb" and items["468"]["name"] == "Blue Orb"
assert pokemon["10077"]["species"] == 382 and pokemon["10078"]["species"] == 383
megas = [form for form in pokemon.values() if form["mega"]]
assert len(megas) == 97
for form in megas:
    stone_id = stone_forms.get(form["id"]) or stone_species.get(form["species"])
    if form["species"] == 384:  # Rayquaza knows Dragon Ascent instead.
        assert stone_id is None
    else:
        assert stone_id is not None, f"Mega Stone missing for {form['name']}"
        assert items[str(stone_id)]["category"] == "Mega Stones"
    base_id = base_forms.get(form["id"])
    if base_id is not None:
        assert pokemon[str(base_id)]["species"] == form["species"]
        assert not pokemon[str(base_id)]["mega"]
    else:
        assert any(candidate["species"] == form["species"] and candidate["default"] for candidate in pokemon.values())
assert stone_forms[10034] != stone_forms[10035]
assert data["learnsets"]["25"].get("6"), "Charizard base learnset needed for Mega inheritance"
assert data["learnsets"]["32"].get("6"), "Champions move reference missing"
for font in ("HubotSans-Regular.woff2", "HubotSans-SemiBold.woff2", "HubotSans-Bold.woff2", "Kalnia-variable.ttf"):
    assert (ROOT / "assets/fonts" / font).is_file(), f"missing font: {font}"
print(f"OK: {len(species)} species, {len(pokemon)} forms, {len(moves)} moves, {len(abilities)} abilities, {len(items)} items, {len(data['learnsets'])} populated game groups")
