const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const tools=require('../team-tools.js');
const context={};vm.createContext(context);
vm.runInContext(fs.readFileSync('data/dex.js','utf8')+';globalThis.DEX=DEX',context);
vm.runInContext(fs.readFileSync('data/mega.js','utf8')+';globalThis.MEGA=MEGA',context);
global.MEGA=context.MEGA;
const dex=context.DEX;
const slot=(pokemonId,itemId=null,moves=[])=>({pokemonId,itemId,moves:[...moves,null,null,null,null].slice(0,4),evs:{},nickname:''});
const team={name:'Élite six ✨',format:'Doubles',game:25,slots:[slot(1,1,[33]),slot(2,1,[22]),slot(3),slot(6),slot(5),slot(10034)]};
const restored=tools.unshare(tools.share(team));
assert.equal(restored.name,team.name);
assert.equal(restored.slots[1].pokemonId,2);
assert.throws(()=>tools.unshare('%%%'));
const result=tools.check(team,dex);
assert.equal(result.analysis.members.length,6);
assert.ok(result.analysis.repeatedItems.length===1);
assert.ok(result.analysis.repeatedSpecies.length===1);
assert.ok(result.analysis.defenses.find(x=>x.type==='Fire').weak.length>=2);
assert.ok(result.findings.some(x=>x.text.includes('repeated')));
const supportOnly={...team,slots:[slot(1,null,[14]),...Array.from({length:5},()=>slot(null))]};
assert.equal(dex.moves[14].category,'Status');
assert.deepEqual(tools.analyze(supportOnly,dex).moveTypes,[]);
assert.equal(tools.analyze(supportOnly,dex).coverage.length,0);
const mixed={...team,slots:[slot(1,null,[14,22]),...Array.from({length:5},()=>slot(null))]};
assert.deepEqual(tools.analyze(mixed,dex).moveTypes,['Grass']);
const missingOrb={...team,slots:[slot(10078),...Array.from({length:5},()=>slot(null))]};
assert.ok(tools.check(missingOrb,dex).findings.some(f=>f.text.includes('Red Orb')));
console.log('OK: team link round-trip, type analysis, duplicate checks');
