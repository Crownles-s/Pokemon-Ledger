const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const stats=require('../team-stats.js');
const context={};vm.createContext(context);
vm.runInContext(fs.readFileSync('data/dex.js','utf8')+';globalThis.DEX=DEX',context);
vm.runInContext(fs.readFileSync('data/mega.js','utf8')+';globalThis.MEGA=MEGA',context);
const dex=context.DEX;
const slot={nature:'Jolly',ivs:{},evs:{speed:252},itemId:null,abilityId:null,moves:[null,null,null,null]};
const garchomp=dex.pokemon[445];
const plain=stats.calculate(garchomp,slot,dex);
assert.equal(plain.trained.speed,169);
assert.equal(plain.effective.speed,169);
const scarf=stats.calculate(garchomp,{...slot,itemId:264},dex);
assert.equal(scarf.effective.speed,253);
assert.ok(scarf.warnings.some(w=>w.includes('first selected move')));
const vest=stats.calculate(garchomp,{...slot,itemId:683,moves:[14,null,null,null]},dex);
assert.equal(vest.effective['special-defense'],Math.floor(vest.trained['special-defense']*1.5));
assert.ok(vest.warnings.some(w=>w.includes('status move')));
const eviolite=stats.calculate(dex.pokemon[1],{...slot,itemId:581},dex);
assert.ok(eviolite.effective.defense>eviolite.trained.defense);
const hugePower=stats.calculate(dex.pokemon[184],{...slot,abilityId:37},dex);
assert.equal(hugePower.effective.attack,hugePower.trained.attack*2);
assert.equal(stats.calculate(dex.pokemon[292],slot,dex).trained.hp,1);
const megaX=stats.project(dex.pokemon[6],{...slot,itemId:699},dex,context.MEGA);
assert.equal(megaX.target.id,10034);
assert.ok(megaX.after.effective.attack>megaX.before.trained.attack);
assert.equal(dex.abilities[megaX.afterAbilityId].name,'Tough Claws');
const megaY=stats.project(dex.pokemon[6],{...slot,itemId:717},dex,context.MEGA);
assert.equal(megaY.target.id,10035);
assert.equal(dex.abilities[megaY.afterAbilityId].name,'Drought');
const missingStone=stats.project(dex.pokemon[10034],slot,dex,context.MEGA);
assert.equal(missingStone.target,null);
assert.equal(missingStone.after.trained.attack,missingStone.before.trained.attack);
assert.ok(missingStone.warnings.some(w=>w.includes('Charizardite X')));
assert.equal(stats.project(dex.pokemon[10034],{...slot,itemId:699},dex,context.MEGA).target.id,10034);
assert.equal(stats.project(dex.pokemon[384],{...slot,moves:[620,null,null,null]},dex,context.MEGA).target.id,10079);
assert.equal(context.MEGA.requiredItem(dex.pokemon[10077]).id,468);
assert.equal(context.MEGA.requiredItem(dex.pokemon[10078]).id,467);
assert.equal(context.MEGA.formForItem(dex.pokemon[6],699).id,10034);
assert.equal(context.MEGA.formForItem(dex.pokemon[6],717).id,10035);
assert.equal(context.MEGA.formForItem(dex.pokemon[382],468).id,10077);
assert.equal(context.MEGA.formForItem(dex.pokemon[383],467).id,10078);
assert.equal(context.MEGA.formForItem(dex.pokemon[6],467),null);
assert.equal(context.MEGA.formForItem(dex.pokemon[6],null),null);
const primalKyogre=stats.project(dex.pokemon[382],{...slot,itemId:468},dex,context.MEGA);
assert.equal(primalKyogre.target.id,10077);
assert.equal(primalKyogre.kind,'PRIMAL REVERSION');
assert.equal(dex.abilities[primalKyogre.afterAbilityId].name,'Primordial Sea');
assert.ok(primalKyogre.after.effective['special-attack']>primalKyogre.before.trained['special-attack']);
assert.equal(stats.project(dex.pokemon[10078],{...slot,itemId:467},dex,context.MEGA).target.id,10078);
assert.equal(stats.project(dex.pokemon[10078],slot,dex,context.MEGA).target,null);
assert.equal(context.MEGA.learnset(dex.pokemon[10077],25).base.id,382);
console.log('OK: level 50 stats, Mega Stones, Primal Orbs, automatic form matching, new abilities, Rayquaza trigger');
